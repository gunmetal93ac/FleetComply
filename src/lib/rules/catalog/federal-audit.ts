/**
 * Federal rule catalog — "DOT audit notice received" (catalog 2026.10.3).
 *
 * There is no single "DOT audit". The workflow separates:
 *   NEW_ENTRANT_AUDIT  — the safety audit in the New Entrant Safety Assurance Program (no rating)
 *   COMPLIANCE_REVIEW  — a compliance review / investigation (may produce a rating or enforcement)
 *   CORRECTIVE_NOTICE  — a notice after a failed new-entrant audit requiring corrective action
 *   RATING_NOTICE      — a notice of a proposed safety rating
 *   UNKNOWN            — the carrier cannot yet tell
 *
 * Facts: reviewType, issuer ("FMCSA" | "STATE" | "UNKNOWN"), carrierClass ("GENERAL" | "PASSENGER_OR_HAZMAT"),
 * proposedRating ("CONDITIONAL" | "UNSATISFACTORY"), deadlineStated, cdlDrivers, noticeReceivedAt (date on the notice),
 * operationType / operatingState.
 *
 * No universal response deadline exists and none is asserted. Fixed periods appear only where the
 * regulation states them (after a failed audit or a proposed rating).
 *
 * Verification: checked on 2026-10-10 against a paragraph-level extraction of the eCFR text
 * current through 2026-10-05.
 */

